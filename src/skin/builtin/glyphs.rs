//! The built-in skin's pixel fonts, drawn as rows of `#` (lit) and `.`.

/// A proportional pixel font: each glyph is as wide as its rows.
pub struct Font {
    pub height: i32,
    /// Blank columns between letters.
    pub spacing: i32,
    glyphs: &'static [(char, [&'static str; 5])],
}

impl Font {
    /// The glyph's rows; characters the font lacks come out blank.
    pub fn glyph(&self, c: char) -> &'static [&'static str; 5] {
        let c = c.to_ascii_uppercase();
        self.glyphs.iter().find(|(g, _)| *g == c).map_or(&BLANK, |(_, rows)| rows)
    }

    #[cfg(test)]
    pub fn has(&self, c: char) -> bool {
        let c = c.to_ascii_uppercase();
        self.glyphs.iter().any(|(g, _)| *g == c)
    }

    /// How far the pen moves after drawing `c`.
    pub fn advance(&self, c: char) -> i32 {
        self.glyph(c)[0].len() as i32 + self.spacing
    }

    /// The width of a line of text, without the space after the last letter.
    pub fn width(&self, text: &str) -> i32 {
        text.chars().map(|c| self.advance(c)).sum::<i32>() - if text.is_empty() { 0 } else { self.spacing }
    }
}

const BLANK: [&str; 5] = ["...", "...", "...", "...", "..."];

/// The main font, used on the displays (it becomes text.bmp) and for
/// title bars. Letters are four pixels wide, except M and W.
pub const TEXT: Font = Font { height: 5, spacing: 1, glyphs: TEXT_GLYPHS };

/// The main font spaced out, for title bars.
pub const TITLE: Font = Font { height: 5, spacing: 2, glyphs: TEXT_GLYPHS };

/// A narrow font for button captions and other small labels.
pub const SMALL: Font = Font { height: 5, spacing: 1, glyphs: SMALL_GLYPHS };

