/// Which of a seven-segment digit's segments are lit, as bits for
/// segments a (top) to g (middle), clockwise from the top.
pub const SEGMENTS: [u8; 10] = [
    0b011_1111, // 0: a b c d e f
    0b000_0110, // 1: b c
    0b101_1011, // 2: a b d e g
    0b100_1111, // 3: a b c d g
    0b110_0110, // 4: b c f g
    0b110_1101, // 5: a c d f g
    0b111_1101, // 6: a c d e f g
    0b000_0111, // 7: a b c
    0b111_1111, // 8: all
    0b110_1111, // 9: a b c d f g
];

/// The segment `bit` (0 = a ... 6 = g) of a 9 x 13 seven-segment digit,
/// as rectangles (x, y, w, h).
pub fn segment(bit: u8) -> &'static [(i32, i32, i32, i32)] {
    match bit {
        0 => &[(2, 0, 5, 2)],          // a: top
        1 => &[(7, 1, 2, 4)],          // b: top right
        2 => &[(7, 7, 2, 5)],          // c: bottom right
        3 => &[(2, 11, 5, 2)],         // d: bottom
        4 => &[(0, 7, 2, 5)],          // e: bottom left
        5 => &[(0, 1, 2, 4)],          // f: top left
        _ => &[(2, 5, 5, 2)],          // g: middle
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyph_rows_are_even() {
        for font in [&TEXT, &SMALL] {
            for (c, rows) in font.glyphs {
                assert!(rows.iter().all(|r| r.len() == rows[0].len()), "glyph {c:?} has uneven rows");
                assert!(rows.iter().all(|r| r.bytes().all(|b| b == b'#' || b == b'.')), "glyph {c:?}");
                if *c != ' ' {
                    assert!(rows.iter().any(|r| r.contains('#')), "glyph {c:?} is blank");
                }
            }
        }
    }

    #[test]
    fn text_glyphs_fit_a_skin_font_cell() {
        // Cells in text.bmp are 5 x 6.
        for (c, rows) in TEXT.glyphs {
            assert!(rows[0].len() <= 5, "glyph {c:?} is too wide");
        }
    }

    #[test]
    fn digits_are_all_different() {
        for (i, a) in SEGMENTS.iter().enumerate() {
            assert!(!SEGMENTS[i + 1..].contains(a), "digit {i} looks like a later one");
        }
    }
}
